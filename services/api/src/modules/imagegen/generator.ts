/**
 * Image generators. `ComfyGenerator` runs the workflows in ./workflows on a ComfyUI server;
 * `DisabledGenerator` is used when no server is configured (the features report "not available"
 * instead of failing). Tests inject their own implementation.
 */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Config } from '../../config.ts';
import { ComfyClient, ComfyError, fillWorkflow, loadWorkflow } from './comfy.ts';

export interface StudioInput {
  /** The garment's own background-free cutout (PNG with alpha). */
  cutoutPng: Buffer;
  /** Spanish/English description used in the prompt, e.g. "chunky knit cardigan, camel". */
  description: string;
  seed: number;
}

export interface AvatarInput {
  face: Buffer;
  body: Buffer;
  /** The outfit's garments composed on one board (flat lay), PNG. */
  outfitBoard: Buffer;
  /** e.g. "puffer jacket over white t-shirt, light-blue jeans, pink flats". */
  description: string;
  seed: number;
}

export interface GeneratorInfo {
  available: boolean;
  studio: boolean;
  avatar: boolean;
  reason: string | null;
  models: { studio: string | null; avatar: string | null };
}

export interface ImageGenerator {
  info(): Promise<GeneratorInfo>;
  studio(input: StudioInput): Promise<Buffer>;
  avatar(input: AvatarInput): Promise<Buffer>;
  /** Any installed workflow (`tryon-accessories`, `avatar-view`…): images by placeholder name. */
  runWorkflow(name: string, images: Record<string, Buffer>, description: string, seed: number): Promise<Buffer>;
  hasWorkflow(name: string): boolean;
}

export { ComfyError };

export class DisabledGenerator implements ImageGenerator {
  async info(): Promise<GeneratorInfo> {
    return { available: false, studio: false, avatar: false, reason: 'El generador de imágenes no está configurado en este servidor.', models: { studio: null, avatar: null } };
  }
  async studio(): Promise<Buffer> {
    throw new ComfyError('El generador de imágenes no está configurado.', false);
  }
  async avatar(): Promise<Buffer> {
    throw new ComfyError('El generador de imágenes no está configurado.', false);
  }
  async runWorkflow(): Promise<Buffer> {
    throw new ComfyError('El generador de imágenes no está configurado.', false);
  }
  hasWorkflow(): boolean {
    return false;
  }
}

const WORKFLOW_DIR = join(dirname(fileURLToPath(import.meta.url)), 'workflows');

/** `workflows/<name>.meta.json`: which model the workflow uses and its licence (shown to users as "generated by"). */
function workflowMeta(name: string): { model: string; license: string } | null {
  const path = join(WORKFLOW_DIR, `${name}.meta.json`);
  if (!existsSync(path) || !existsSync(join(WORKFLOW_DIR, `${name}.json`))) return null;
  return JSON.parse(readFileSync(path, 'utf8')) as { model: string; license: string };
}

export class ComfyGenerator implements ImageGenerator {
  private readonly client: ComfyClient;
  private readonly timeoutMs: number;
  private readonly studioWorkflow: string;
  private readonly avatarWorkflow: string;
  constructor(opts: { url: string; timeoutMs: number; studioWorkflow: string; avatarWorkflow: string; fetcher?: typeof fetch }) {
    this.client = new ComfyClient(opts.url, opts.fetcher);
    this.timeoutMs = opts.timeoutMs;
    this.studioWorkflow = opts.studioWorkflow;
    this.avatarWorkflow = opts.avatarWorkflow;
  }

  async info(): Promise<GeneratorInfo> {
    const studio = workflowMeta(this.studioWorkflow);
    const avatar = workflowMeta(this.avatarWorkflow);
    const up = await this.client.health();
    return {
      available: up && (!!studio || !!avatar),
      studio: up && !!studio,
      avatar: up && !!avatar,
      reason: !up ? 'El generador de imágenes no responde ahora mismo.' : !studio && !avatar ? 'No hay workflows de generación instalados.' : null,
      models: { studio: studio?.model ?? null, avatar: avatar?.model ?? null },
    };
  }

  async studio(input: StudioInput): Promise<Buffer> {
    const name = await this.client.uploadImage(input.cutoutPng, `dressit-studio-${input.seed}.png`);
    const wf = fillWorkflow(loadWorkflow(this.studioWorkflow), { INPUT_IMAGE: name, DESCRIPTION: input.description, SEED: input.seed });
    return this.client.run(wf, this.timeoutMs);
  }

  async avatar(input: AvatarInput): Promise<Buffer> {
    const [face, body, board] = await Promise.all([
      this.client.uploadImage(input.face, `dressit-face-${input.seed}.jpg`),
      this.client.uploadImage(input.body, `dressit-body-${input.seed}.jpg`),
      this.client.uploadImage(input.outfitBoard, `dressit-outfit-${input.seed}.png`),
    ]);
    const wf = fillWorkflow(loadWorkflow(this.avatarWorkflow), { FACE_IMAGE: face, BODY_IMAGE: body, OUTFIT_IMAGE: board, DESCRIPTION: input.description, SEED: input.seed });
    return this.client.run(wf, this.timeoutMs);
  }

  async runWorkflow(name: string, images: Record<string, Buffer>, description: string, seed: number): Promise<Buffer> {
    const names: Record<string, string> = {};
    for (const [key, data] of Object.entries(images)) names[key] = await this.client.uploadImage(data, `dressit-${name}-${key.toLowerCase()}-${seed}.png`);
    return this.client.run(fillWorkflow(loadWorkflow(name), { ...names, DESCRIPTION: description, SEED: seed }), this.timeoutMs);
  }

  hasWorkflow(name: string): boolean {
    return workflowMeta(name) !== null;
  }

  modelFor(kind: 'studio' | 'avatar'): string | null {
    return workflowMeta(kind === 'studio' ? this.studioWorkflow : this.avatarWorkflow)?.model ?? null;
  }
}

export function createImageGenerator(cfg: Config): ImageGenerator {
  return cfg.IMAGEGEN_COMFY_URL
    ? new ComfyGenerator({ url: cfg.IMAGEGEN_COMFY_URL, timeoutMs: cfg.IMAGEGEN_TIMEOUT_MS, studioWorkflow: cfg.IMAGEGEN_STUDIO_WORKFLOW, avatarWorkflow: cfg.IMAGEGEN_AVATAR_WORKFLOW })
    : new DisabledGenerator();
}
